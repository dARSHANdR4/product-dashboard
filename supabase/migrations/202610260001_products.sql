create table if not exists public.products (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  category text not null,
  price numeric(12,2) not null check (price >= 0),
  "discountPercentage" numeric(6,2) not null default 0,
  rating numeric(4,2) not null default 0,
  stock integer not null default 0 check (stock >= 0),
  tags text[] not null default '{}',
  brand text not null default '',
  sku text not null unique,
  weight numeric(10,2) not null default 0,
  dimensions jsonb not null default '{"width":0,"height":0,"depth":0}'::jsonb,
  "warrantyInformation" text not null default '',
  "shippingInformation" text not null default '',
  "availabilityStatus" text not null default 'In Stock',
  reviews jsonb not null default '[]'::jsonb,
  "returnPolicy" text not null default '',
  "minimumOrderQuantity" integer not null default 1,
  meta jsonb not null default '{}'::jsonb,
  images text[] not null default '{}',
  thumbnail text not null default '',
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create index if not exists products_category_idx on public.products(category);
create index if not exists products_title_idx on public.products(title);
create index if not exists products_created_at_idx on public.products("createdAt");

create or replace function public.set_product_updated_at()
returns trigger language plpgsql as $$
begin
  new."updatedAt" = now();
  return new;
end;
$$;

drop trigger if exists products_updated_at on public.products;
create trigger products_updated_at before update on public.products
for each row execute function public.set_product_updated_at();

-- Do not expose the table directly to browser clients. All access goes through
-- server-side Next.js routes using the service-role key, which must never be public.
alter table public.products enable row level security;
