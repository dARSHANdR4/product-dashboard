-- Phase 0 / Identity foundation
-- Supabase Auth owns credentials in auth.users. This migration adds application
-- profiles and database-backed staff roles without changing existing products.
begin;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  avatar_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists private.roles (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists private.permissions (
  id bigint generated by default as identity primary key,
  code text not null unique,
  description text not null
);

create table if not exists private.role_permissions (
  role_id bigint not null references private.roles(id) on delete cascade,
  permission_id bigint not null references private.permissions(id) on delete cascade,
  primary key (role_id, permission_id)
);

create table if not exists private.user_roles (
  user_id uuid not null references auth.users(id) on delete cascade,
  role_id bigint not null references private.roles(id) on delete cascade,
  assigned_by uuid references auth.users(id) on delete set null,
  assigned_at timestamptz not null default now(),
  primary key (user_id, role_id)
);

comment on schema private is
  'Internal authorization tables. Keep this schema out of Supabase Data API exposed schemas.';
comment on table public.profiles is
  'Non-privileged profile fields only. Staff roles are stored separately in private.user_roles.';
comment on table private.user_roles is
  'Staff role assignments. No authenticated client receives INSERT, UPDATE, or DELETE privileges.';

insert into private.roles (code, name) values
  ('owner', 'Owner'),
  ('admin', 'Administrator'),
  ('product_manager', 'Product Manager'),
  ('inventory_manager', 'Inventory Manager'),
  ('order_manager', 'Order Manager')
on conflict (code) do update set name = excluded.name;

insert into private.permissions (code, description) values
  ('products.read', 'Read product catalogue and product records'),
  ('products.manage', 'Create and update product records'),
  ('categories.manage', 'Create and manage product categories'),
  ('inventory.read', 'Read stock levels and inventory movements'),
  ('inventory.manage', 'Adjust inventory and manage stock movements'),
  ('orders.read', 'Read customer orders'),
  ('orders.manage', 'Manage order fulfilment and status'),
  ('customers.read', 'Read customer account information'),
  ('customers.manage', 'Manage customer account support actions'),
  ('promotions.manage', 'Manage coupons and promotions'),
  ('analytics.read', 'Read business analytics'),
  ('staff.manage', 'Manage staff accounts and role assignments'),
  ('settings.manage', 'Manage store settings'),
  ('audit.read', 'Read security and business audit logs')
on conflict (code) do update set description = excluded.description;

-- Owner receives every permission. Admin deliberately cannot manage staff or
-- security-sensitive store settings. Functional roles receive narrow scopes.
insert into private.role_permissions (role_id, permission_id)
select r.id, p.id
from private.roles r
cross join private.permissions p
where r.code = 'owner'
on conflict do nothing;

insert into private.role_permissions (role_id, permission_id)
select r.id, p.id
from private.roles r
cross join private.permissions p
where r.code = 'admin'
  and p.code not in ('staff.manage', 'settings.manage')
on conflict do nothing;

insert into private.role_permissions (role_id, permission_id)
select r.id, p.id
from private.roles r
join private.permissions p on p.code in ('products.read', 'products.manage', 'categories.manage')
where r.code = 'product_manager'
on conflict do nothing;

insert into private.role_permissions (role_id, permission_id)
select r.id, p.id
from private.roles r
join private.permissions p on p.code in ('inventory.read', 'inventory.manage')
where r.code = 'inventory_manager'
on conflict do nothing;

insert into private.role_permissions (role_id, permission_id)
select r.id, p.id
from private.roles r
join private.permissions p on p.code in ('orders.read', 'orders.manage', 'customers.read')
where r.code = 'order_manager'
on conflict do nothing;

create or replace function private.has_permission(requested_permission text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from private.user_roles ur
    join private.role_permissions rp on rp.role_id = ur.role_id
    join private.permissions p on p.id = rp.permission_id
    where ur.user_id = (select auth.uid())
      and p.code = requested_permission
  );
$$;

revoke all on function private.has_permission(text) from public, anon;
grant execute on function private.has_permission(text) to authenticated;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (
    new.id,
    nullif(trim(coalesce(new.raw_user_meta_data ->> 'full_name', '')), '')
  )
  on conflict (id) do nothing;
  -- Never copy user metadata into roles or permissions.
  return new;
end;
$$;

revoke all on function public.handle_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

alter table public.profiles enable row level security;
alter table private.roles enable row level security;
alter table private.permissions enable row level security;
alter table private.role_permissions enable row level security;
alter table private.user_roles enable row level security;

drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own
  on public.profiles for select to authenticated
  using ((select auth.uid()) = id);

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own
  on public.profiles for update to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

drop policy if exists user_roles_select_own on private.user_roles;
create policy user_roles_select_own
  on private.user_roles for select to authenticated
  using ((select auth.uid()) = user_id);

-- Remove inherited/default client access, then grant only the operations above.
revoke all on public.profiles from anon, authenticated;
grant select, update on public.profiles to authenticated;

revoke all on private.roles, private.permissions, private.role_permissions, private.user_roles
  from public, anon, authenticated;
grant select on private.user_roles to authenticated;

commit;
